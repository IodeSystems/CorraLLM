package service

import (
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// Installed is one unit (or LaunchAgent) that `corrallm service install` wrote.
type Installed struct {
	Name  string // unit name without .service; the part after LabelPrefix for launchd
	Agent bool   // runs `corrallm agent`, not `serve`
}

// generatedMark is the header every unit and plist this package writes starts
// with. Only those are ours: a hand-written unit that happens to be named
// corrallm-something is not `--all`'s to stop.
const generatedMark = "Generated by `corrallm service install"

// FindInstalled lists the units in dir that this package wrote, servers first
// (an agent reconnects to its server, so a restart of everything brings the
// server up before the agents look for it), then by name.
func FindInstalled(dir string, launchd bool) ([]Installed, error) {
	pattern, suffix := "*.service", ".service"
	if launchd {
		pattern, suffix = LabelPrefix+"*.plist", ".plist"
	}
	paths, err := filepath.Glob(filepath.Join(dir, pattern))
	if err != nil {
		return nil, err
	}
	var out []Installed
	for _, p := range paths {
		b, err := os.ReadFile(p)
		if err != nil || !strings.Contains(string(b), generatedMark) {
			continue
		}
		name := strings.TrimSuffix(filepath.Base(p), suffix)
		in := Installed{Name: strings.TrimPrefix(name, LabelPrefix)}
		if launchd {
			args := PlistArgs(string(b))
			in.Agent = len(args) > 1 && args[1] == "agent"
		} else {
			in.Agent = UnitIsAgent(string(b))
		}
		out = append(out, in)
	}
	sort.Slice(out, func(i, j int) bool {
		if out[i].Agent != out[j].Agent {
			return !out[i].Agent
		}
		return out[i].Name < out[j].Name
	})
	return out, nil
}

// UnitIsAgent reports whether a unit this package wrote runs `corrallm agent`.
func UnitIsAgent(unit string) bool {
	return strings.Contains(unit, generatedMark+" --agent`")
}
