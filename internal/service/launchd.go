package service

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// launchd is the macOS counterpart of the systemd unit: a per-user LaunchAgent
// in ~/Library/LaunchAgents, loaded into the gui/<uid> domain.
//
// It cannot carry everything the systemd unit does, and the gaps are on
// purpose rather than forgotten:
//
//   - No validate-before-start step. launchd has no ExecStartPre; `corrallm
//     service restart` validates before it stops anything, which is the case
//     the pre-step exists for.
//   - No reload verb. Send SIGHUP to the job's pid (launchctl kill HUP
//     gui/<uid>/<label>) — launchd signals the main process only.
//   - No handoff (`service upgrade`). launchd tracks the pid it started and
//     has no way to be told the main process moved; the successor would be an
//     orphan it cannot stop. `serve` refuses a handoff under launchd.
//   - No OOMPolicy: macOS has no OOM killer that picks a victim the same way.

// LabelPrefix namespaces the launchd label. The label is also the plist's
// file name, and `launchctl print gui/<uid>/<label>` is how an operator finds
// the job.
const LabelPrefix = "com.iodesystems."

// Label is the launchd label for a unit name.
func (u Unit) Label() string {
	name := u.Name
	if name == "" {
		name = DefaultName
	}
	return LabelPrefix + name
}

// PlistFileName is the file this job installs as.
func (u Unit) PlistFileName() string { return u.Label() + ".plist" }

// LaunchAgentsDir is where launchd reads per-user jobs from.
func LaunchAgentsDir() (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, "Library", "LaunchAgents"), nil
}

// LaunchdLogPath is where the job's stdout and stderr go. launchd has no
// journal; `corrallm service logs` reads this file.
func LaunchdLogPath(name string) (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, "Library", "Logs", "corrallm", name+".log"), nil
}

func xmlEscape(s string) string {
	r := strings.NewReplacer("&", "&amp;", "<", "&lt;", ">", "&gt;", `"`, "&quot;", "'", "&apos;")
	return r.Replace(s)
}

// RenderPlist produces the LaunchAgent. logPath receives stdout and stderr.
func (u Unit) RenderPlist(logPath string) string {
	verb := "serve"
	if u.Agent {
		verb = "agent"
	}
	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by ` + "`corrallm service install`" + `. Edits are overwritten on reinstall. -->
<plist version="1.0">
<dict>
`)
	kv := func(k, v string) { fmt.Fprintf(&b, "\t<key>%s</key>\n\t<string>%s</string>\n", k, xmlEscape(v)) }
	kv("Label", u.Label())
	b.WriteString("\t<key>ProgramArguments</key>\n\t<array>\n")
	for _, a := range append([]string{u.Exec, verb}, u.Args...) {
		fmt.Fprintf(&b, "\t\t<string>%s</string>\n", xmlEscape(a))
	}
	b.WriteString("\t</array>\n")
	if u.WorkingDir != "" {
		kv("WorkingDirectory", u.WorkingDir)
	}
	if len(u.Env) > 0 {
		b.WriteString("\t<key>EnvironmentVariables</key>\n\t<dict>\n")
		for _, e := range u.Env {
			k, v, _ := strings.Cut(e, "=")
			fmt.Fprintf(&b, "\t\t<key>%s</key>\n\t\t<string>%s</string>\n", xmlEscape(k), xmlEscape(v))
		}
		b.WriteString("\t</dict>\n")
	}
	kv("StandardOutPath", logPath)
	kv("StandardErrorPath", logPath)

	// Start at login, and again after a crash — but not after a clean exit,
	// which is how a stop or a drain ends. Same as Restart=on-failure.
	b.WriteString("\t<key>RunAtLoad</key>\n\t<true/>\n")
	b.WriteString("\t<key>KeepAlive</key>\n\t<dict>\n\t\t<key>SuccessfulExit</key>\n\t\t<false/>\n\t</dict>\n")
	// launchd's default is 10 s between restarts; a config that fails at start
	// should not spin faster than that.
	b.WriteString("\t<key>ThrottleInterval</key>\n\t<integer>10</integer>\n")

	if u.Agent {
		// Stop the AGENT only. Its backends stay up for the next agent to
		// adopt; launchd's default kills the job's whole process group when
		// the main process exits. Same as KillMode=process on systemd.
		b.WriteString("\t<key>AbandonProcessGroup</key>\n\t<true/>\n")
		// The agent's own exit is quick: it ends tool runs (≤10s) and leaves.
		b.WriteString("\t<key>ExitTimeOut</key>\n\t<integer>30</integer>\n")
	} else {
		// A drain waits for in-flight work; launchd's default 20 s turns a
		// graceful shutdown into a SIGKILL that strands backends.
		b.WriteString("\t<key>ExitTimeOut</key>\n\t<integer>90</integer>\n")
	}
	// Interactive, not Background: Background jobs get throttled CPU and I/O,
	// which a model server must not.
	kv("ProcessType", "Interactive")
	b.WriteString("</dict>\n</plist>\n")
	return b.String()
}

// InstallPlist writes the LaunchAgent into dir and reports the path.
func (u Unit) InstallPlist(dir, logPath string) (string, error) {
	if u.Exec == "" {
		return "", fmt.Errorf("no executable path for the job")
	}
	if !filepath.IsAbs(u.Exec) {
		return "", fmt.Errorf("executable %q must be an absolute path: launchd does not search $PATH", u.Exec)
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", err
	}
	if err := os.MkdirAll(filepath.Dir(logPath), 0o755); err != nil {
		return "", err
	}
	p := filepath.Join(dir, u.PlistFileName())
	if err := os.WriteFile(p, []byte(u.RenderPlist(logPath)), 0o644); err != nil {
		return "", err
	}
	return p, nil
}

// PlistArgs recovers ProgramArguments from a plist this package wrote, so
// `service restart` can find the --config to validate.
func PlistArgs(plist string) []string {
	_, rest, ok := strings.Cut(plist, "<key>ProgramArguments</key>")
	if !ok {
		return nil
	}
	rest, _, _ = strings.Cut(rest, "</array>")
	var out []string
	un := strings.NewReplacer("&lt;", "<", "&gt;", ">", "&quot;", `"`, "&apos;", "'", "&amp;", "&")
	for {
		_, after, ok := strings.Cut(rest, "<string>")
		if !ok {
			return out
		}
		v, after2, _ := strings.Cut(after, "</string>")
		out = append(out, un.Replace(v))
		rest = after2
	}
}

// PlistEnv recovers EnvironmentVariables from a plist this package wrote.
func PlistEnv(plist string) map[string]string {
	out := map[string]string{}
	_, rest, ok := strings.Cut(plist, "<key>EnvironmentVariables</key>")
	if !ok {
		return out
	}
	rest, _, _ = strings.Cut(rest, "</dict>")
	un := strings.NewReplacer("&lt;", "<", "&gt;", ">", "&quot;", `"`, "&apos;", "'", "&amp;", "&")
	for {
		_, a, ok := strings.Cut(rest, "<key>")
		if !ok {
			return out
		}
		k, a, _ := strings.Cut(a, "</key>")
		_, a, ok = strings.Cut(a, "<string>")
		if !ok {
			return out
		}
		v, a, _ := strings.Cut(a, "</string>")
		out[un.Replace(k)] = un.Replace(v)
		rest = a
	}
}

// UnitEnv recovers Environment= lines from a unit this package wrote.
func UnitEnv(unit string) map[string]string {
	out := map[string]string{}
	for _, line := range strings.Split(unit, "\n") {
		if kv, ok := strings.CutPrefix(line, "Environment="); ok {
			if k, v, ok := strings.Cut(kv, "="); ok {
				out[k] = v
			}
		}
	}
	return out
}
